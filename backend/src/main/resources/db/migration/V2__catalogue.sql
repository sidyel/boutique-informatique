-- =====================================================================

CREATE TABLE categorie (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                varchar(120) NOT NULL,
    slug               varchar(140) NOT NULL,
    parent_id          bigint REFERENCES categorie (id) ON DELETE RESTRICT,
    description        text,
    image_url          varchar(255),
    banniere_url       varchar(255),
    position           integer      NOT NULL DEFAULT 0,
    actif              boolean      NOT NULL DEFAULT true,
    meta_titre         varchar(70),
    meta_description   varchar(170),
    texte_seo          text,
    categorie_google   varchar(255),
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_categorie_slug UNIQUE (slug),
    CONSTRAINT ck_categorie_pas_son_propre_parent CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX ix_categorie_parent ON categorie (parent_id, position);

CREATE TABLE marque (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                varchar(80)  NOT NULL,
    slug               varchar(100) NOT NULL,
    logo_url           varchar(255),
    description        text,
    meta_titre         varchar(70),
    meta_description   varchar(170),
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_marque_slug UNIQUE (slug)
);

CREATE TABLE produit (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                 varchar(200) NOT NULL,
    slug                varchar(220) NOT NULL,
    marque_id           bigint       NOT NULL REFERENCES marque (id) ON DELETE RESTRICT,
    categorie_id        bigint       NOT NULL REFERENCES categorie (id) ON DELETE RESTRICT,
    description_courte  varchar(500),
    description_longue  text,
    etat                varchar(20)  NOT NULL DEFAULT 'NEUF',
    garantie_mois       integer      NOT NULL DEFAULT 0,
    gtin                varchar(14),
    mpn                 varchar(70),
    actif               boolean      NOT NULL DEFAULT true,
    mis_en_avant        boolean      NOT NULL DEFAULT false,
    meta_titre          varchar(70),
    meta_description    varchar(170),
    note_moyenne        numeric(3,2) NOT NULL DEFAULT 0,
    nombre_avis         integer      NOT NULL DEFAULT 0,
    -- Agrégats des variantes actives, maintenus par trigger (tris et filtres sans jointure)
    prix_minimum        bigint,
    stock_total         integer      NOT NULL DEFAULT 0,
    date_creation       timestamptz  NOT NULL DEFAULT now(),
    date_modification   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_produit_slug UNIQUE (slug),
    CONSTRAINT ck_produit_etat CHECK (etat IN ('NEUF', 'RECONDITIONNE', 'OCCASION')),
    CONSTRAINT ck_produit_garantie CHECK (garantie_mois >= 0),
    CONSTRAINT ck_produit_note CHECK (note_moyenne BETWEEN 0 AND 5),
    CONSTRAINT ck_produit_gtin CHECK (gtin IS NULL OR gtin ~ '^[0-9]{8,14}$')
);
CREATE INDEX ix_produit_categorie_actif ON produit (categorie_id, actif);
CREATE INDEX ix_produit_marque ON produit (marque_id);
CREATE INDEX ix_produit_prix_minimum ON produit (prix_minimum) WHERE actif;
CREATE INDEX ix_produit_mis_en_avant ON produit (date_creation DESC) WHERE actif AND mis_en_avant;

CREATE TABLE variante_produit (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id         bigint       NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
    sku                varchar(64)  NOT NULL,
    libelle            varchar(150) NOT NULL,
    attributs          jsonb        NOT NULL DEFAULT '{}'::jsonb,
    prix               bigint       NOT NULL,
    prix_barre         bigint,
    stock              integer      NOT NULL DEFAULT 0,
    seuil_alerte       integer      NOT NULL DEFAULT 2,
    poids_grammes      integer,
    actif              boolean      NOT NULL DEFAULT true,
    version            bigint       NOT NULL DEFAULT 0,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_variante_produit_sku UNIQUE (sku),
    CONSTRAINT ck_variante_prix CHECK (prix >= 0),
    CONSTRAINT ck_variante_prix_barre CHECK (prix_barre IS NULL OR prix_barre > 0),
    CONSTRAINT ck_variante_stock CHECK (stock >= 0),
    CONSTRAINT ck_variante_seuil CHECK (seuil_alerte >= 0),
    CONSTRAINT ck_variante_poids CHECK (poids_grammes IS NULL OR poids_grammes > 0)
);
CREATE INDEX ix_variante_produit_produit ON variante_produit (produit_id);
CREATE INDEX ix_variante_produit_stock_faible ON variante_produit (stock) WHERE actif AND stock <= seuil_alerte;

CREATE TABLE media_produit (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id         bigint       NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
    variante_id        bigint       REFERENCES variante_produit (id) ON DELETE CASCADE,
    type               varchar(20)  NOT NULL,
    url                varchar(500) NOT NULL,
    id_public          varchar(255),
    url_miniature      varchar(500),
    texte_alternatif   varchar(255) NOT NULL,
    position           integer      NOT NULL DEFAULT 0,
    principal          boolean      NOT NULL DEFAULT false,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_media_type CHECK (type IN ('IMAGE', 'VIDEO_FICHIER', 'VIDEO_YOUTUBE')),
    CONSTRAINT ck_media_principal_est_image CHECK (NOT principal OR type = 'IMAGE')
);
CREATE INDEX ix_media_produit_produit ON media_produit (produit_id, position);
-- Une seule image principale par produit
CREATE UNIQUE INDEX uk_media_produit_principal ON media_produit (produit_id) WHERE principal;

CREATE TABLE definition_caracteristique (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categorie_id       bigint       NOT NULL REFERENCES categorie (id) ON DELETE CASCADE,
    cle                varchar(60)  NOT NULL,
    libelle            varchar(100) NOT NULL,
    unite              varchar(20),
    type               varchar(20)  NOT NULL,
    groupe             varchar(60)  NOT NULL,
    filtrable          boolean      NOT NULL DEFAULT false,
    cle_recherche      boolean      NOT NULL DEFAULT false,
    ordre              integer      NOT NULL DEFAULT 0,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_definition_caracteristique UNIQUE (categorie_id, cle),
    CONSTRAINT ck_definition_cle CHECK (cle ~ '^[a-z][a-z0-9_]*$'),
    CONSTRAINT ck_definition_type CHECK (type IN ('TEXTE', 'NOMBRE', 'BOOLEEN', 'LISTE'))
);

CREATE TABLE valeur_caracteristique (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id         bigint        NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
    variante_id        bigint        REFERENCES variante_produit (id) ON DELETE CASCADE,
    definition_id      bigint        NOT NULL REFERENCES definition_caracteristique (id) ON DELETE CASCADE,
    valeur_texte       varchar(255),
    valeur_nombre      numeric(14,4),
    valeur_booleen     boolean,
    date_creation      timestamptz   NOT NULL DEFAULT now(),
    date_modification  timestamptz   NOT NULL DEFAULT now(),
    -- Une valeur par caractéristique et par produit (ou par variante qui la surcharge)
    CONSTRAINT uk_valeur_caracteristique UNIQUE NULLS NOT DISTINCT (produit_id, variante_id, definition_id),
    CONSTRAINT ck_valeur_renseignee
        CHECK (num_nonnulls(valeur_texte, valeur_nombre, valeur_booleen) = 1)
);
CREATE INDEX ix_valeur_caracteristique_produit ON valeur_caracteristique (produit_id);
-- Filtres dynamiques : « RAM ≥ 16 Go », « socket = AM5 »
CREATE INDEX ix_valeur_caracteristique_filtre_nombre ON valeur_caracteristique (definition_id, valeur_nombre);
CREATE INDEX ix_valeur_caracteristique_filtre_texte ON valeur_caracteristique (definition_id, valeur_texte);

CREATE TABLE historique_slug (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_entite        varchar(20)  NOT NULL,
    ancien_slug        varchar(220) NOT NULL,
    entite_id          bigint       NOT NULL,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_historique_slug UNIQUE (type_entite, ancien_slug),
    CONSTRAINT ck_historique_slug_type CHECK (type_entite IN ('PRODUIT', 'CATEGORIE', 'MARQUE', 'ARTICLE'))
);

-- ---------------------------------------------------------------------
-- Agrégats du produit (prix_minimum, stock_total) recalculés à chaque
-- insertion, modification ou suppression d'une variante.
-- Fait en base pour rester exact quel que soit le chemin d'écriture
-- (application, import CSV, script SQL).
-- ---------------------------------------------------------------------
CREATE FUNCTION recalculer_agregats_produit(p_produit_id bigint) RETURNS void
LANGUAGE sql AS $$
    UPDATE produit p
       SET prix_minimum = a.prix_minimum,
           stock_total  = a.stock_total
      FROM (SELECT min(prix) FILTER (WHERE actif)                   AS prix_minimum,
                   coalesce(sum(stock) FILTER (WHERE actif), 0)::int AS stock_total
              FROM variante_produit
             WHERE produit_id = p_produit_id) a
     WHERE p.id = p_produit_id
       AND (p.prix_minimum IS DISTINCT FROM a.prix_minimum OR p.stock_total <> a.stock_total);
$$;

CREATE FUNCTION declencheur_agregats_variante() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM recalculer_agregats_produit(NEW.produit_id);
    END IF;
    IF TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND OLD.produit_id <> NEW.produit_id) THEN
        PERFORM recalculer_agregats_produit(OLD.produit_id);
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER tr_variante_agregats_insertion_suppression
    AFTER INSERT OR DELETE ON variante_produit
    FOR EACH ROW EXECUTE FUNCTION declencheur_agregats_variante();

-- En mise à jour, seulement si une colonne qui compte a changé
CREATE TRIGGER tr_variante_agregats_modification
    AFTER UPDATE OF prix, stock, actif, produit_id ON variante_produit
    FOR EACH ROW EXECUTE FUNCTION declencheur_agregats_variante();
