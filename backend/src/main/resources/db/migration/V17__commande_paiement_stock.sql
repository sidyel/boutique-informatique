-- =====================================================================
-- V17 — Commande, réservation du stock et paiement à la livraison (phase 4b).
-- =====================================================================

-- E-mail facultatif pour un invité (le téléphone reste obligatoire) ; nom de la personne qui commande.
ALTER TABLE commande ALTER COLUMN email_client DROP NOT NULL;
ALTER TABLE commande
    ADD COLUMN nom_client varchar(120),
    ADD CONSTRAINT ck_commande_email CHECK (email_client IS NULL OR email_client ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$');

-- « Mobile money » : le client choisit Wave, Orange Money ou Free Money sur la page du prestataire.
ALTER TABLE commande DROP CONSTRAINT ck_commande_mode_paiement;
ALTER TABLE commande ADD CONSTRAINT ck_commande_mode_paiement
    CHECK (mode_paiement IN ('MOBILE_MONEY', 'CARTE_BANCAIRE', 'A_LA_LIVRAISON', 'WAVE', 'ORANGE_MONEY', 'FREE_MONEY'));

-- Paiement à la livraison : commande en attente de l'appel du service client.
ALTER TABLE commande DROP CONSTRAINT ck_commande_statut;
ALTER TABLE commande ADD CONSTRAINT ck_commande_statut CHECK (statut IN ('EN_ATTENTE_PAIEMENT',
    'EN_ATTENTE_CONFIRMATION', 'CONFIRMEE', 'PAYEE', 'EN_PREPARATION', 'EXPEDIEE', 'LIVREE', 'ANNULEE', 'REMBOURSEE'));

-- Fin de la réservation du stock : mobile money non payé, ou commande à la livraison non confirmée.
-- Renseignée seulement tant que la commande attend (EN_ATTENTE_PAIEMENT, EN_ATTENTE_CONFIRMATION).
ALTER TABLE commande
    ADD COLUMN expire_le timestamptz,
    -- Lien de suivi sans compte (page /suivi/{jeton}) : 256 bits aléatoires, base64url. Gardé en clair pour
    -- pouvoir renvoyer le même lien (réponse rejouée, e-mail) ; la page n'expose que des données masquées.
    ADD COLUMN jeton_suivi varchar(43),
    -- Événement « achat » des régies publicitaires déjà émis (une seule fois par commande).
    ADD COLUMN achat_suivi_le timestamptz,
    -- Premier contact (premier clic) en plus du dernier, déjà dans les colonnes utm_*.
    ADD COLUMN premiere_source varchar(100),
    ADD COLUMN premier_medium varchar(100),
    ADD COLUMN premiere_campagne varchar(150),
    ADD COLUMN premiere_page_arrivee varchar(500),
    ADD CONSTRAINT ck_commande_jeton_suivi CHECK (jeton_suivi IS NULL OR jeton_suivi ~ '^[A-Za-z0-9_-]{43}$');
CREATE UNIQUE INDEX uk_commande_jeton_suivi ON commande (jeton_suivi) WHERE jeton_suivi IS NOT NULL;
CREATE INDEX ix_commande_expiration ON commande (expire_le)
    WHERE statut IN ('EN_ATTENTE_PAIEMENT', 'EN_ATTENTE_CONFIRMATION');
-- Commandes en attente de confirmation par téléphone (plafond par numéro)
CREATE INDEX ix_commande_attente_confirmation ON commande (telephone_client)
    WHERE statut = 'EN_ATTENTE_CONFIRMATION';

-- Libération de la réservation (annulation, expiration) : mouvement positif lié à la commande.
ALTER TABLE mouvement_stock DROP CONSTRAINT ck_mouvement_stock_type;
ALTER TABLE mouvement_stock ADD CONSTRAINT ck_mouvement_stock_type
    CHECK (type IN ('ENTREE', 'SORTIE_VENTE', 'AJUSTEMENT', 'RETOUR', 'ANNULATION'));
ALTER TABLE mouvement_stock DROP CONSTRAINT ck_mouvement_stock_sens;
ALTER TABLE mouvement_stock ADD CONSTRAINT ck_mouvement_stock_sens CHECK (
    (type = 'ENTREE' AND quantite > 0)
    OR (type = 'SORTIE_VENTE' AND quantite < 0 AND commande_id IS NOT NULL)
    OR (type IN ('RETOUR', 'ANNULATION') AND quantite > 0 AND commande_id IS NOT NULL)
    OR type = 'AJUSTEMENT');

-- Page de paiement du prestataire : « Reprendre le paiement » crée un nouveau paiement pour la même commande.
ALTER TABLE paiement ADD COLUMN url_paiement varchar(500);

-- Réglages réglables sans redéploiement.
ALTER TABLE parametres_site
    ADD COLUMN paiement_livraison_actif boolean NOT NULL DEFAULT true,
    ADD COLUMN paiement_livraison_montant_max bigint NOT NULL DEFAULT 500000,
    ADD COLUMN paiement_livraison_max_non_confirmees integer NOT NULL DEFAULT 2,
    ADD COLUMN paiement_livraison_delai_annulation_heures integer NOT NULL DEFAULT 24,
    ADD COLUMN delai_paiement_mobile_minutes integer NOT NULL DEFAULT 30,
    ADD CONSTRAINT ck_parametres_site_paiement_livraison CHECK (
        paiement_livraison_montant_max >= 0
        AND paiement_livraison_max_non_confirmees BETWEEN 1 AND 20
        AND paiement_livraison_delai_annulation_heures BETWEEN 1 AND 168
        AND delai_paiement_mobile_minutes BETWEEN 5 AND 1440);

-- Idempotence de POST /api/commandes : une clé par tentative de commande (en-tête Idempotency-Key),
-- liée au client (compte ou panier invité). Durée de vie limitée (purgée).
CREATE TABLE cle_idempotence (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- « u:{utilisateur} » ou « i:{empreinte du jeton du panier invité} »
    portee        varchar(80)  NOT NULL,
    cle           varchar(64)  NOT NULL,
    -- Empreinte de la demande : la même clé avec un contenu différent est refusée
    empreinte     varchar(64)  NOT NULL,
    commande_id   bigint       REFERENCES commande (id) ON DELETE CASCADE,
    date_creation timestamptz  NOT NULL DEFAULT now(),
    expire_le     timestamptz  NOT NULL,
    CONSTRAINT uk_cle_idempotence UNIQUE (portee, cle)
);
CREATE INDEX ix_cle_idempotence_expiration ON cle_idempotence (expire_le);
