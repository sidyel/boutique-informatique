-- Relecture de sécurité I1 + M1 (ADR 0003 §8) : le verrouillage après échecs de connexion est compté par
-- couple (e-mail, IP) et non plus par compte. Un attaquant qui connaît l'e-mail d'une victime ne peut plus
-- l'empêcher de se connecter depuis une autre IP.
--
-- La table est indexée par l'EMPREINTE de l'e-mail saisi (SHA-256 de l'adresse normalisée), que le compte
-- existe ou non : une connexion échouée exécute exactement la même écriture dans les deux cas, sans écart de
-- temps de réponse qui révélerait l'existence du compte. Aucune adresse en clair.
CREATE TABLE echec_connexion (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empreinte_email    varchar(64)  NOT NULL,
    adresse_ip         varchar(45)  NOT NULL,
    echecs             integer      NOT NULL DEFAULT 0,
    verrouille_jusqua  timestamptz,
    date_creation      timestamptz  NOT NULL,
    date_modification  timestamptz  NOT NULL,
    CONSTRAINT uk_echec_connexion UNIQUE (empreinte_email, adresse_ip),
    CONSTRAINT ck_echec_connexion_empreinte CHECK (empreinte_email ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_echec_connexion_echecs CHECK (echecs >= 0)
);
-- Purge quotidienne des lignes anciennes
CREATE INDEX ix_echec_connexion_modification ON echec_connexion (date_modification);

-- Lien de déverrouillage envoyé au titulaire au verrouillage de son compte (1 h, usage unique)
CREATE TABLE jeton_deverrouillage (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    empreinte          varchar(64)  NOT NULL,
    date_expiration    timestamptz  NOT NULL,
    date_utilisation   timestamptz,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_jeton_deverrouillage_empreinte UNIQUE (empreinte),
    CONSTRAINT ck_jeton_deverrouillage_empreinte CHECK (empreinte ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_jeton_deverrouillage_utilisateur ON jeton_deverrouillage (utilisateur_id);

-- Ancien verrouillage par compte : remplacé par echec_connexion
ALTER TABLE utilisateur
    DROP CONSTRAINT ck_utilisateur_echecs,
    DROP COLUMN echecs_connexion,
    DROP COLUMN verrouille_jusqua;
