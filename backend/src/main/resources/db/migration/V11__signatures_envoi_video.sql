-- =====================================================================
-- V11 : signatures d'envoi des vidéos (ADR 0005)
-- =====================================================================

-- Chaque signature émise pour un envoi direct navigateur → Cloudinary est enregistrée. Une vidéo envoyée
-- mais jamais déclarée (navigateur fermé en cours de route) reste sur Cloudinary sans ligne dans
-- media_produit : la tâche de nettoyage de la phase 9 retrouvera ces fichiers grâce aux signatures
-- expirées et jamais utilisées.
-- Pas de clé étrangère vers produit : la trace doit survivre à la suppression du produit.
CREATE TABLE signature_envoi_video (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id         bigint       NOT NULL,
    id_public          varchar(255) NOT NULL,
    dossier            varchar(255) NOT NULL,
    date_expiration    timestamptz  NOT NULL,
    date_utilisation   timestamptz,
    date_creation      timestamptz  NOT NULL,
    date_modification  timestamptz  NOT NULL,
    CONSTRAINT uk_signature_envoi_video_id_public UNIQUE (id_public)
);
-- Recherche des signatures expirées jamais utilisées (nettoyage)
CREATE INDEX ix_signature_envoi_video_non_utilisee ON signature_envoi_video (date_expiration)
    WHERE date_utilisation IS NULL;
