-- =====================================================================
-- V6 — Après-vente et engagement : avis, liste de souhaits, alertes,
--      demandes SAV et leurs messages, mouvements de stock.
-- Les données d'un compte supprimé sont anonymisées, pas supprimées
-- (utilisateur_id / auteur_id en ON DELETE SET NULL, nom affiché copié).
-- =====================================================================

CREATE TABLE avis (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produit_id         bigint       NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
    utilisateur_id     bigint       REFERENCES utilisateur (id) ON DELETE SET NULL,
    nom_auteur         varchar(80)  NOT NULL,
    note               integer      NOT NULL,
    titre              varchar(120),
    commentaire        text,
    photos             jsonb        NOT NULL DEFAULT '[]'::jsonb,
    achat_verifie      boolean      NOT NULL DEFAULT false,
    statut             varchar(20)  NOT NULL DEFAULT 'EN_ATTENTE',
    reponse_boutique   text,
    date_reponse       timestamptz,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    -- Un avis par client et par produit (les avis anonymisés, sans utilisateur, ne comptent pas)
    CONSTRAINT uk_avis_produit_utilisateur UNIQUE (produit_id, utilisateur_id),
    CONSTRAINT ck_avis_note CHECK (note BETWEEN 1 AND 5),
    CONSTRAINT ck_avis_statut CHECK (statut IN ('EN_ATTENTE', 'APPROUVE', 'REJETE')),
    CONSTRAINT ck_avis_photos CHECK (jsonb_typeof(photos) = 'array' AND jsonb_array_length(photos) <= 5)
);
CREATE INDEX ix_avis_produit_publie ON avis (produit_id, date_creation DESC) WHERE statut = 'APPROUVE';
CREATE INDEX ix_avis_a_moderer ON avis (date_creation) WHERE statut = 'EN_ATTENTE';
CREATE INDEX ix_avis_utilisateur ON avis (utilisateur_id);

-- ---------------------------------------------------------------------
-- produit.note_moyenne et produit.nombre_avis : avis APPROUVÉS uniquement,
-- recalculés par trigger (même principe que prix_minimum en V2).
-- ---------------------------------------------------------------------
CREATE FUNCTION recalculer_note_produit(p_produit_id bigint) RETURNS void
LANGUAGE sql AS $$
    UPDATE produit p
       SET note_moyenne = a.note_moyenne,
           nombre_avis  = a.nombre_avis
      FROM (SELECT coalesce(round(avg(note), 2), 0) AS note_moyenne,
                   count(*)::int                    AS nombre_avis
              FROM avis
             WHERE produit_id = p_produit_id AND statut = 'APPROUVE') a
     WHERE p.id = p_produit_id
       AND (p.note_moyenne <> a.note_moyenne OR p.nombre_avis <> a.nombre_avis);
$$;

CREATE FUNCTION declencheur_note_avis() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM recalculer_note_produit(NEW.produit_id);
    END IF;
    IF TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND OLD.produit_id <> NEW.produit_id) THEN
        PERFORM recalculer_note_produit(OLD.produit_id);
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER tr_avis_note_insertion_suppression
    AFTER INSERT OR DELETE ON avis
    FOR EACH ROW EXECUTE FUNCTION declencheur_note_avis();

CREATE TRIGGER tr_avis_note_modification
    AFTER UPDATE OF note, statut, produit_id ON avis
    FOR EACH ROW EXECUTE FUNCTION declencheur_note_avis();

