CREATE TABLE element_liste_souhaits (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    variante_id        bigint       NOT NULL REFERENCES variante_produit (id) ON DELETE CASCADE,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_liste_souhaits UNIQUE (utilisateur_id, variante_id)
);
CREATE INDEX ix_liste_souhaits_variante ON element_liste_souhaits (variante_id);

CREATE TABLE alerte_produit (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              varchar(254) NOT NULL,
    variante_id        bigint       NOT NULL REFERENCES variante_produit (id) ON DELETE CASCADE,
    type               varchar(20)  NOT NULL,
    prix_cible         bigint,
    envoyee            boolean      NOT NULL DEFAULT false,
    date_envoi         timestamptz,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_alerte_email_minuscules CHECK (email = lower(email)),
    CONSTRAINT ck_alerte_type CHECK (type IN ('RETOUR_EN_STOCK', 'BAISSE_DE_PRIX')),
    -- IS NOT NULL explicite : un CHECK évalué à NULL serait accepté
    CONSTRAINT ck_alerte_prix_cible CHECK (
        (type = 'BAISSE_DE_PRIX' AND prix_cible IS NOT NULL AND prix_cible > 0) OR (type = 'RETOUR_EN_STOCK' AND prix_cible IS NULL)),
    CONSTRAINT ck_alerte_envoi CHECK (envoyee = (date_envoi IS NOT NULL))
);
-- Une seule alerte en attente par e-mail, variante et type
CREATE UNIQUE INDEX uk_alerte_en_attente ON alerte_produit (email, variante_id, type) WHERE NOT envoyee;
-- Tâche d'envoi : alertes en attente d'une variante qui revient en stock ou baisse de prix
CREATE INDEX ix_alerte_a_envoyer ON alerte_produit (variante_id, type) WHERE NOT envoyee;

