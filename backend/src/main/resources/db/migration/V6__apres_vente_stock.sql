CREATE TABLE demande_sav (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id        bigint       NOT NULL REFERENCES commande (id) ON DELETE RESTRICT,
    ligne_commande_id  bigint       REFERENCES ligne_commande (id) ON DELETE RESTRICT,
    motif              varchar(20)  NOT NULL,
    description        text         NOT NULL,
    photos             jsonb        NOT NULL DEFAULT '[]'::jsonb,
    statut             varchar(20)  NOT NULL DEFAULT 'OUVERTE',
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_demande_sav_motif CHECK (motif IN ('DEFECTUEUX', 'NON_CONFORME', 'RETRACTATION', 'GARANTIE')),
    CONSTRAINT ck_demande_sav_statut
        CHECK (statut IN ('OUVERTE', 'EN_COURS', 'EN_ATTENTE_CLIENT', 'RESOLUE', 'REFUSEE')),
    CONSTRAINT ck_demande_sav_photos CHECK (jsonb_typeof(photos) = 'array' AND jsonb_array_length(photos) <= 10)
);
CREATE INDEX ix_demande_sav_commande ON demande_sav (commande_id);
CREATE INDEX ix_demande_sav_en_cours ON demande_sav (statut, date_creation) WHERE statut NOT IN ('RESOLUE', 'REFUSEE');

-- La ligne concernée appartient bien à la commande de la demande
CREATE FUNCTION verifier_ligne_demande_sav() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.ligne_commande_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM ligne_commande WHERE id = NEW.ligne_commande_id AND commande_id = NEW.commande_id) THEN
        RAISE EXCEPTION 'La ligne % n''appartient pas à la commande %', NEW.ligne_commande_id, NEW.commande_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_demande_sav_ligne_de_la_commande';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tr_demande_sav_ligne
    BEFORE INSERT OR UPDATE OF commande_id, ligne_commande_id ON demande_sav
    FOR EACH ROW EXECUTE FUNCTION verifier_ligne_demande_sav();

CREATE TABLE message_sav (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id         bigint       NOT NULL REFERENCES demande_sav (id) ON DELETE CASCADE,
    auteur_id          bigint       REFERENCES utilisateur (id) ON DELETE SET NULL,
    nom_auteur         varchar(120) NOT NULL,
    de_la_boutique     boolean      NOT NULL,
    note_interne       boolean      NOT NULL DEFAULT false,
    contenu            text         NOT NULL,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    -- Seule l'équipe peut écrire une note interne
    CONSTRAINT ck_message_sav_note_interne CHECK (NOT note_interne OR de_la_boutique)
);
CREATE INDEX ix_message_sav_demande ON message_sav (demande_id, date_creation);

-- ---------------------------------------------------------------------
-- Journal du stock (immuable)
-- ---------------------------------------------------------------------
CREATE TABLE mouvement_stock (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variante_id        bigint       NOT NULL REFERENCES variante_produit (id) ON DELETE CASCADE,
    quantite           integer      NOT NULL,
    stock_apres        integer      NOT NULL,
    type               varchar(20)  NOT NULL,
    motif              varchar(255),
    commande_id        bigint       REFERENCES commande (id) ON DELETE RESTRICT,
    auteur             varchar(254) NOT NULL,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_mouvement_stock_type CHECK (type IN ('ENTREE', 'SORTIE_VENTE', 'AJUSTEMENT', 'RETOUR')),
    CONSTRAINT ck_mouvement_stock_quantite CHECK (quantite <> 0),
    CONSTRAINT ck_mouvement_stock_apres CHECK (stock_apres >= 0),
    -- Le signe suit le type ; une vente ou un retour vient d'une commande
    CONSTRAINT ck_mouvement_stock_sens CHECK (
        (type = 'ENTREE' AND quantite > 0)
        OR (type = 'SORTIE_VENTE' AND quantite < 0 AND commande_id IS NOT NULL)
        OR (type = 'RETOUR' AND quantite > 0 AND commande_id IS NOT NULL)
        OR type = 'AJUSTEMENT')
);
CREATE INDEX ix_mouvement_stock_variante ON mouvement_stock (variante_id, date_creation DESC);
CREATE INDEX ix_mouvement_stock_commande ON mouvement_stock (commande_id) WHERE commande_id IS NOT NULL;

-- Immuable : une erreur se corrige par un mouvement d'AJUSTEMENT, jamais en modifiant l'historique.
-- (La suppression d'une variante jamais commandée emporte ses mouvements par cascade.)
CREATE FUNCTION interdire_modification_mouvement() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Un mouvement de stock ne se modifie pas : enregistrer un mouvement d''ajustement'
        USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_mouvement_stock_immuable';
END;
$$;

CREATE TRIGGER tr_mouvement_stock_immuable
    BEFORE UPDATE ON mouvement_stock
    FOR EACH ROW EXECUTE FUNCTION interdire_modification_mouvement();
