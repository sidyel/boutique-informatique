-- =====================================================================
-- V21 — Factures, avoirs et encaissements (phase 4d).
--
-- Pièces comptables IMMUABLES : tout est figé à l'émission (vendeur, régime de TVA, client, lignes, montants, PDF).
-- Modifier parametres_site, le catalogue ou le client ensuite ne change jamais une pièce émise. Un déclencheur
-- interdit UPDATE et DELETE sur ces tables ; une correction se fait par un avoir. Conservation : 10 ans (OHADA).
-- Montants en FCFA (bigint). Prix du site TTC ; TVA extraite du TTC (méthode des plus forts restes, ADR 0008).
-- =====================================================================

-- ---------------------------------------------------------------------
-- Mentions légales du vendeur et régime de TVA : réglables par l'admin (parametres_site)
-- ---------------------------------------------------------------------
ALTER TABLE parametres_site
    ADD COLUMN facture_raison_sociale varchar(160),
    ADD COLUMN facture_ninea          varchar(40),
    ADD COLUMN facture_rccm           varchar(60),
    ADD COLUMN facture_adresse_siege  varchar(255),
    -- Par défaut « TVA non applicable » en attendant la confirmation du régime fiscal par le comptable
    ADD COLUMN facture_regime_tva     varchar(20)  NOT NULL DEFAULT 'NON_APPLICABLE',
    -- Points de base : 1800 = 18 %
    ADD COLUMN facture_taux_tva_bp    integer      NOT NULL DEFAULT 1800,
    ADD COLUMN facture_mention_tva    varchar(255) NOT NULL DEFAULT 'TVA non applicable',
    ADD CONSTRAINT ck_parametres_site_regime_tva CHECK (facture_regime_tva IN ('ASSUJETTI', 'NON_APPLICABLE')),
    ADD CONSTRAINT ck_parametres_site_taux_tva CHECK (facture_taux_tva_bp BETWEEN 0 AND 10000);

-- ---------------------------------------------------------------------
-- Numérotation continue SANS TROU (une table verrouillée, pas une séquence : ADR 0004 §4)
-- ---------------------------------------------------------------------
CREATE TABLE compteur_document (
    type            varchar(3) NOT NULL,
    annee           integer    NOT NULL,
    dernier_numero  bigint     NOT NULL DEFAULT 0,
    PRIMARY KEY (type, annee),
    CONSTRAINT ck_compteur_document_type CHECK (type IN ('FAC', 'AV')),
    CONSTRAINT ck_compteur_document_numero CHECK (dernier_numero >= 0)
);

-- ---------------------------------------------------------------------
-- Facture : une par commande, émise au paiement confirmé (en ligne) ou à la livraison (encaissement)
-- ---------------------------------------------------------------------
CREATE TABLE facture (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                  varchar(20)  NOT NULL,
    commande_id             bigint       NOT NULL REFERENCES commande (id) ON DELETE RESTRICT,
    date_emission           timestamptz  NOT NULL,
    -- Vendeur tel qu'il était à l'émission (peut être vide en développement)
    vendeur_raison_sociale  varchar(160),
    vendeur_ninea           varchar(40),
    vendeur_rccm            varchar(60),
    vendeur_adresse         varchar(255),
    regime_tva              varchar(20)  NOT NULL,
    taux_tva_bp             integer      NOT NULL,
    mention_tva             varchar(255) NOT NULL,
    -- Client tel qu'il était à l'émission
    client_nom              varchar(120),
    client_telephone        varchar(13)  NOT NULL,
    client_email            varchar(254),
    client_adresse          varchar(500),
    mode_paiement           varchar(20)  NOT NULL,
    total_ttc               bigint       NOT NULL,
    total_ht                bigint       NOT NULL,
    total_tva               bigint       NOT NULL,
    pdf                     bytea        NOT NULL,
    pdf_sha256              char(64)     NOT NULL,
    CONSTRAINT uk_facture_numero UNIQUE (numero),
    CONSTRAINT uk_facture_commande UNIQUE (commande_id),
    CONSTRAINT ck_facture_numero CHECK (numero ~ '^FAC-[0-9]{4}-[0-9]{6,}$'),
    CONSTRAINT ck_facture_regime CHECK (regime_tva IN ('ASSUJETTI', 'NON_APPLICABLE')),
    CONSTRAINT ck_facture_taux CHECK (taux_tva_bp BETWEEN 0 AND 10000),
    CONSTRAINT ck_facture_totaux CHECK (total_ttc >= 0 AND total_ht + total_tva = total_ttc),
    CONSTRAINT ck_facture_sans_tva CHECK (regime_tva = 'ASSUJETTI' OR total_tva = 0),
    CONSTRAINT ck_facture_sha256 CHECK (pdf_sha256 ~ '^[0-9a-f]{64}$')
);

CREATE TABLE ligne_facture (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facture_id          bigint       NOT NULL REFERENCES facture (id) ON DELETE RESTRICT,
    rang                integer      NOT NULL,
    type                varchar(10)  NOT NULL,
    ligne_commande_id   bigint       REFERENCES ligne_commande (id) ON DELETE RESTRICT,
    sku                 varchar(80),
    designation         varchar(300) NOT NULL,
    quantite            integer      NOT NULL,
    prix_unitaire_ttc   bigint       NOT NULL,
    -- Brut, part de la remise du code promo (répartie au prorata sur les articles), net
    total_brut_ttc      bigint       NOT NULL,
    remise_ttc          bigint       NOT NULL DEFAULT 0,
    total_ttc           bigint       NOT NULL,
    total_ht            bigint       NOT NULL,
    montant_tva         bigint       NOT NULL,
    CONSTRAINT uk_ligne_facture_rang UNIQUE (facture_id, rang),
    CONSTRAINT ck_ligne_facture_type CHECK (type IN ('ARTICLE', 'LIVRAISON')),
    CONSTRAINT ck_ligne_facture_quantite CHECK (quantite >= 1),
    CONSTRAINT ck_ligne_facture_remise CHECK (remise_ttc >= 0 AND (type = 'ARTICLE' OR remise_ttc = 0)),
    CONSTRAINT ck_ligne_facture_net CHECK (total_ttc >= 0 AND total_brut_ttc - remise_ttc = total_ttc),
    CONSTRAINT ck_ligne_facture_ht CHECK (total_ht + montant_tva = total_ttc)
);
CREATE INDEX ix_ligne_facture_ligne_commande ON ligne_facture (ligne_commande_id);

-- ---------------------------------------------------------------------
-- Avoir : référence la facture d'origine, total ou partiel ; pièce comptable seule (pas de remise en stock)
-- Les montants sont portés en positif (c'est un crédit) ; l'identité du vendeur et du client est celle de la facture.
-- ---------------------------------------------------------------------
CREATE TABLE avoir (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero         varchar(20)  NOT NULL,
    facture_id     bigint       NOT NULL REFERENCES facture (id) ON DELETE RESTRICT,
    date_emission  timestamptz  NOT NULL,
    motif          varchar(500) NOT NULL,
    emis_par       varchar(120) NOT NULL,
    total_ttc      bigint       NOT NULL,
    total_ht       bigint       NOT NULL,
    total_tva      bigint       NOT NULL,
    pdf            bytea        NOT NULL,
    pdf_sha256     char(64)     NOT NULL,
    CONSTRAINT uk_avoir_numero UNIQUE (numero),
    CONSTRAINT ck_avoir_numero CHECK (numero ~ '^AV-[0-9]{4}-[0-9]{6,}$'),
    CONSTRAINT ck_avoir_totaux CHECK (total_ttc > 0 AND total_ht + total_tva = total_ttc),
    CONSTRAINT ck_avoir_sha256 CHECK (pdf_sha256 ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_avoir_facture ON avoir (facture_id);

CREATE TABLE ligne_avoir (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avoir_id          bigint  NOT NULL REFERENCES avoir (id) ON DELETE RESTRICT,
    ligne_facture_id  bigint  NOT NULL REFERENCES ligne_facture (id) ON DELETE RESTRICT,
    quantite          integer NOT NULL,
    total_ttc         bigint  NOT NULL,
    total_ht          bigint  NOT NULL,
    montant_tva       bigint  NOT NULL,
    CONSTRAINT uk_ligne_avoir UNIQUE (avoir_id, ligne_facture_id),
    CONSTRAINT ck_ligne_avoir_quantite CHECK (quantite >= 1),
    CONSTRAINT ck_ligne_avoir_montants CHECK (total_ttc > 0 AND total_ht + montant_tva = total_ttc)
);
CREATE INDEX ix_ligne_avoir_ligne_facture ON ligne_avoir (ligne_facture_id);

-- ---------------------------------------------------------------------
-- Encaissement réel (paiement à la livraison) : montant reçu, moyen, qui, quand. Plusieurs lignes possibles par
-- commande (encaissement complémentaire lors d'une régularisation, phase 6).
-- ---------------------------------------------------------------------
CREATE TABLE encaissement (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id         bigint       NOT NULL REFERENCES commande (id) ON DELETE RESTRICT,
    montant             bigint       NOT NULL,
    moyen               varchar(30)  NOT NULL,
    moyen_precision     varchar(200),
    motif_ecart         varchar(30),
    motif_ecart_precision varchar(200),
    encaisse_par_id     bigint       REFERENCES utilisateur (id) ON DELETE SET NULL,
    encaisse_par_nom    varchar(120) NOT NULL,
    date_encaissement   timestamptz  NOT NULL,
    CONSTRAINT ck_encaissement_montant CHECK (montant >= 0),
    CONSTRAINT ck_encaissement_moyen CHECK (moyen IN ('ESPECES', 'WAVE_LIVREUR', 'ORANGE_MONEY_LIVREUR', 'AUTRE')),
    CONSTRAINT ck_encaissement_moyen_precision CHECK (moyen <> 'AUTRE' OR length(btrim(coalesce(moyen_precision, ''))) > 0),
    CONSTRAINT ck_encaissement_motif CHECK (motif_ecart IS NULL
        OR motif_ecart IN ('MONNAIE_MANQUANTE', 'ARTICLE_CONTESTE', 'REMISE_ACCORDEE', 'AUTRE')),
    CONSTRAINT ck_encaissement_motif_precision CHECK (motif_ecart IS DISTINCT FROM 'AUTRE'
        OR length(btrim(coalesce(motif_ecart_precision, ''))) > 0)
);
CREATE INDEX ix_encaissement_commande ON encaissement (commande_id);

-- Écart d'encaissement à régulariser : total de la commande − montant encaissé (jamais négatif : un montant
-- supérieur au total est refusé). Régularisé plus tard par un avoir ou un encaissement complémentaire.
ALTER TABLE commande
    ADD COLUMN ecart_encaissement   bigint      NOT NULL DEFAULT 0,
    ADD COLUMN ecart_regularise_le  timestamptz,
    ADD CONSTRAINT ck_commande_ecart_encaissement CHECK (ecart_encaissement >= 0);
CREATE INDEX ix_commande_ecart_a_regulariser ON commande (id)
    WHERE ecart_encaissement > 0 AND ecart_regularise_le IS NULL;

-- ---------------------------------------------------------------------
-- Immuabilité : jamais de modification ni de suppression d'une pièce émise
-- ---------------------------------------------------------------------
CREATE FUNCTION interdire_modification_piece() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'Pièce comptable immuable : % interdit sur % (corriger par un avoir)', TG_OP, TG_TABLE_NAME
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER tr_facture_immuable BEFORE UPDATE OR DELETE ON facture
    FOR EACH ROW EXECUTE FUNCTION interdire_modification_piece();
CREATE TRIGGER tr_ligne_facture_immuable BEFORE UPDATE OR DELETE ON ligne_facture
    FOR EACH ROW EXECUTE FUNCTION interdire_modification_piece();
CREATE TRIGGER tr_avoir_immuable BEFORE UPDATE OR DELETE ON avoir
    FOR EACH ROW EXECUTE FUNCTION interdire_modification_piece();
CREATE TRIGGER tr_ligne_avoir_immuable BEFORE UPDATE OR DELETE ON ligne_avoir
    FOR EACH ROW EXECUTE FUNCTION interdire_modification_piece();
CREATE TRIGGER tr_encaissement_immuable BEFORE UPDATE OR DELETE ON encaissement
    FOR EACH ROW EXECUTE FUNCTION interdire_modification_piece();
