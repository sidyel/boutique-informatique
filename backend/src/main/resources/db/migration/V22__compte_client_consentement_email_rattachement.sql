-- 1. Consentement ----------------------------------------------------
ALTER TABLE utilisateur ADD COLUMN source_consentement varchar(30);
ALTER TABLE utilisateur ADD CONSTRAINT ck_utilisateur_source_consentement
    CHECK (source_consentement IS NULL OR source_consentement IN ('INSCRIPTION', 'COMPTE', 'ADMIN'));
-- Comptes existants : la date de consentement n'a été enregistrée qu'à l'inscription
UPDATE utilisateur SET source_consentement = 'INSCRIPTION' WHERE date_consentement IS NOT NULL;

-- Historique en ajout seul : chaque acceptation ou retrait est daté et sa source conservée
CREATE TABLE historique_consentement (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id  bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    consentement    boolean      NOT NULL,
    source          varchar(30)  NOT NULL,
    date_decision   timestamptz  NOT NULL,
    CONSTRAINT ck_historique_consentement_source CHECK (source IN ('INSCRIPTION', 'COMPTE', 'ADMIN'))
);
CREATE INDEX ix_historique_consentement_utilisateur ON historique_consentement (utilisateur_id, date_decision DESC);
INSERT INTO historique_consentement (utilisateur_id, consentement, source, date_decision)
SELECT id, consentement_marketing, 'INSCRIPTION', date_consentement
  FROM utilisateur WHERE date_consentement IS NOT NULL;

-- 2. Changement d'e-mail ---------------------------------------------
CREATE TABLE changement_email (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id          bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    ancien_email            varchar(254) NOT NULL,
    nouvel_email            varchar(254) NOT NULL,
    -- Seules les empreintes SHA-256 des jetons sont stockées (comme les autres jetons)
    empreinte_confirmation  varchar(64)  NOT NULL,
    empreinte_signalement   varchar(64)  NOT NULL,
    statut                  varchar(20)  NOT NULL DEFAULT 'EN_ATTENTE',
    -- EN_ATTENTE : fin de validité du lien de confirmation ; CONFIRME : fin du délai pour signaler un changement non sollicité
    date_expiration         timestamptz  NOT NULL,
    date_confirmation       timestamptz,
    date_signalement        timestamptz,
    date_creation           timestamptz  NOT NULL DEFAULT now(),
    date_modification       timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_changement_email_confirmation UNIQUE (empreinte_confirmation),
    CONSTRAINT uk_changement_email_signalement UNIQUE (empreinte_signalement),
    CONSTRAINT ck_changement_email_statut CHECK (statut IN ('EN_ATTENTE', 'CONFIRME', 'ANNULE', 'REVERTI')),
    CONSTRAINT ck_changement_email_minuscules CHECK (ancien_email = lower(ancien_email) AND nouvel_email = lower(nouvel_email))
);
-- Une seule demande en attente par compte
CREATE UNIQUE INDEX uk_changement_email_en_attente ON changement_email (utilisateur_id) WHERE statut = 'EN_ATTENTE';
CREATE INDEX ix_changement_email_utilisateur ON changement_email (utilisateur_id, date_creation DESC);

-- 3. Rattachement des commandes invité --------------------------------
CREATE TABLE rattachement_commande (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id     bigint       NOT NULL REFERENCES commande (id) ON DELETE CASCADE,
    utilisateur_id  bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    -- Ce qui a déclenché le rattachement : VERIFICATION_EMAIL, CHANGEMENT_EMAIL, REINITIALISATION, CONNEXION
    declencheur     varchar(30)  NOT NULL,
    date_rattachement timestamptz NOT NULL,
    CONSTRAINT uk_rattachement_commande UNIQUE (commande_id)
);
CREATE INDEX ix_rattachement_commande_utilisateur ON rattachement_commande (utilisateur_id);
