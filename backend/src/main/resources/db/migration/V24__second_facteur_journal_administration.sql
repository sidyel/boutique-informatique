-- =====================================================================
-- V24 — Sécurité de l'administration (phase 6a, ADR 0009)
--  1. Second facteur TOTP des comptes internes : secret chiffré, dernier pas accepté (anti-rejeu), codes de secours.
--  2. Étape de connexion : jeton opaque (empreinte) entre le mot de passe et le code, secret d'enrôlement en attente.
--  3. Réauthentification (code TOTP récent) liée à la session.
--  4. Journal des actions d'administration : immuable, purge au bout de 3 ans.
-- =====================================================================

-- 1. Second facteur ----------------------------------------------------
ALTER TABLE utilisateur
    ADD COLUMN totp_secret_chiffre         text,
    ADD COLUMN totp_active_le              timestamptz,
    ADD COLUMN totp_dernier_pas            bigint,
    ADD COLUMN codes_secours_confirmes_le  timestamptz;

-- Un second facteur actif a toujours un secret ; un secret n'est jamais écrit sans date d'activation
ALTER TABLE utilisateur ADD CONSTRAINT ck_utilisateur_totp_coherent
    CHECK ((totp_secret_chiffre IS NULL) = (totp_active_le IS NULL));

CREATE TABLE code_secours (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    empreinte          varchar(64)  NOT NULL,
    date_utilisation   timestamptz,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_code_secours_empreinte UNIQUE (empreinte),
    CONSTRAINT ck_code_secours_empreinte CHECK (empreinte ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_code_secours_utilisateur ON code_secours (utilisateur_id);

-- 2. Étape de connexion -------------------------------------------------
CREATE TABLE etape_connexion (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id           bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    empreinte                varchar(64)  NOT NULL,
    etape                    varchar(40)  NOT NULL,
    secret_en_attente_chiffre text,
    essais                   integer      NOT NULL DEFAULT 0,
    adresse_ip               varchar(45),
    user_agent               varchar(300),
    date_expiration          timestamptz  NOT NULL,
    date_limite              timestamptz  NOT NULL,
    date_utilisation         timestamptz,
    date_creation            timestamptz  NOT NULL DEFAULT now(),
    date_modification        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_etape_connexion_empreinte UNIQUE (empreinte),
    CONSTRAINT ck_etape_connexion_empreinte CHECK (empreinte ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_etape_connexion_etape CHECK (etape IN ('ENROLEMENT_REQUIS', 'CODE_REQUIS', 'CODES_SECOURS_A_CONFIRMER'))
);
CREATE INDEX ix_etape_connexion_utilisateur ON etape_connexion (utilisateur_id);

-- 3. Réauthentification -------------------------------------------------
-- Une ligne par session (famille de jetons de rafraîchissement) : valable jusqu'à l'instant indiqué
CREATE TABLE reauthentification (
    famille        uuid         PRIMARY KEY,
    utilisateur_id bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    valide_jusqu   timestamptz  NOT NULL
);
CREATE INDEX ix_reauthentification_utilisateur ON reauthentification (utilisateur_id);

-- 4. Journal des actions d'administration -------------------------------
-- Pas de clé étrangère vers utilisateur : la ligne doit survivre à tout, avec une copie de l'identité de l'auteur.
CREATE TABLE journal_administration (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_action        timestamptz  NOT NULL,
    utilisateur_id     bigint,
    utilisateur_email  varchar(254) NOT NULL,
    role               varchar(30)  NOT NULL,
    action             varchar(80)  NOT NULL,
    entite_type        varchar(60),
    entite_id          varchar(80),
    avant              jsonb,
    apres              jsonb,
    details            varchar(500),
    adresse_ip         varchar(45),
    methode            varchar(10),
    chemin             varchar(300),
    statut_http        integer,
    generique          boolean      NOT NULL DEFAULT false
);
CREATE INDEX ix_journal_administration_date ON journal_administration (date_action DESC);
CREATE INDEX ix_journal_administration_utilisateur ON journal_administration (utilisateur_id, date_action DESC);
CREATE INDEX ix_journal_administration_action ON journal_administration (action, date_action DESC);
CREATE INDEX ix_journal_administration_entite ON journal_administration (entite_type, entite_id);

-- Immuable : aucune modification ; suppression seulement des lignes de plus de 3 ans (purge nocturne)
CREATE FUNCTION proteger_journal_administration() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF TG_OP = 'DELETE' AND OLD.date_action < now() - interval '3 years' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'Journal d''administration immuable : % interdit (seules les lignes de plus de 3 ans peuvent être purgées)', TG_OP
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER tr_journal_administration_immuable BEFORE UPDATE OR DELETE ON journal_administration
    FOR EACH ROW EXECUTE FUNCTION proteger_journal_administration();
-- TRUNCATE contourne les déclencheurs de ligne : interdit aussi
CREATE FUNCTION interdire_vidage_journal_administration() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'Journal d''administration immuable : TRUNCATE interdit'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER tr_journal_administration_pas_de_vidage BEFORE TRUNCATE ON journal_administration
    FOR EACH STATEMENT EXECUTE FUNCTION interdire_vidage_journal_administration();
