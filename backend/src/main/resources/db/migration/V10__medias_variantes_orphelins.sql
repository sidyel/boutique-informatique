-- =====================================================================
-- V10 : médias des variantes supprimées et fichiers orphelins (ADR 0005)
-- =====================================================================

-- Une variante supprimée ne supprime plus ses photos : elles restent rattachées au produit
-- (variante_id remis à NULL). Une photo coûte du travail (prise de vue, retouche) et peut servir
-- à une autre variante ; c'est à l'équipe de décider de la supprimer.
ALTER TABLE media_produit DROP CONSTRAINT media_produit_variante_id_fkey;
ALTER TABLE media_produit
    ADD CONSTRAINT fk_media_produit_variante
        FOREIGN KEY (variante_id) REFERENCES variante_produit (id) ON DELETE SET NULL;
-- Sans index, chaque suppression de variante parcourrait toute la table des médias
CREATE INDEX ix_media_produit_variante ON media_produit (variante_id) WHERE variante_id IS NOT NULL;

-- Fichiers Cloudinary dont la suppression a échoué après plusieurs essais : ils ne sont plus référencés
-- par le site mais occupent encore le stockage (et restent accessibles par leur URL). Une tâche planifiée
-- les supprimera (phase 9) ; en attendant, la liste est consultable en base.
CREATE TABLE media_orphelin (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_public          varchar(255) NOT NULL,
    type_ressource     varchar(10)  NOT NULL,
    origine            varchar(200) NOT NULL,
    derniere_erreur    varchar(500),
    tentatives         integer      NOT NULL DEFAULT 0,
    date_creation      timestamptz  NOT NULL,
    date_modification  timestamptz  NOT NULL,
    CONSTRAINT uk_media_orphelin_id_public UNIQUE (id_public),
    CONSTRAINT ck_media_orphelin_type CHECK (type_ressource IN ('IMAGE', 'VIDEO')),
    CONSTRAINT ck_media_orphelin_tentatives CHECK (tentatives >= 0)
);
