-- =====================================================================
-- V3 — Comptes : utilisateurs, carnet d'adresses et jetons d'authentification.
-- Téléphones au format E.164 sénégalais (+221 suivi de 70/75/76/77/78/33 et 7 chiffres),
-- normalisés par l'application (TelephoneSenegal) et revérifiés ici.
-- =====================================================================

CREATE TABLE utilisateur (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                   varchar(254) NOT NULL,
    mot_de_passe_hash       varchar(100) NOT NULL,
    prenom                  varchar(80)  NOT NULL,
    nom                     varchar(80)  NOT NULL,
    telephone               varchar(13),
    role                    varchar(30)  NOT NULL DEFAULT 'CLIENT',
    actif                   boolean      NOT NULL DEFAULT true,
    email_verifie           boolean      NOT NULL DEFAULT false,
    consentement_marketing  boolean      NOT NULL DEFAULT false,
    date_consentement       timestamptz,
    echecs_connexion        integer      NOT NULL DEFAULT 0,
    verrouille_jusqua       timestamptz,
    date_creation           timestamptz  NOT NULL DEFAULT now(),
    date_modification       timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_utilisateur_email UNIQUE (email),
    -- L'e-mail est stocké en minuscules : l'unicité est donc insensible à la casse
    CONSTRAINT ck_utilisateur_email_minuscules CHECK (email = lower(email)),
    CONSTRAINT ck_utilisateur_role
        CHECK (role IN ('CLIENT', 'SERVICE_CLIENT', 'GESTIONNAIRE_STOCK', 'ADMIN', 'SUPER_ADMIN')),
    CONSTRAINT ck_utilisateur_echecs CHECK (echecs_connexion >= 0),
    CONSTRAINT ck_utilisateur_telephone CHECK (telephone ~ '^\+221(70|75|76|77|78|33)[0-9]{7}$')
);
CREATE INDEX ix_utilisateur_telephone ON utilisateur (telephone) WHERE telephone IS NOT NULL;

CREATE TABLE adresse (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    libelle            varchar(40)  NOT NULL,
    nom_complet        varchar(120) NOT NULL,
    telephone          varchar(13)  NOT NULL,
    ville              varchar(80)  NOT NULL,
    quartier           varchar(80)  NOT NULL,
    adresse_ligne      varchar(255),
    point_de_repere    varchar(255),
    par_defaut         boolean      NOT NULL DEFAULT false,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_adresse_telephone CHECK (telephone ~ '^\+221(70|75|76|77|78|33)[0-9]{7}$')
);
CREATE INDEX ix_adresse_utilisateur ON adresse (utilisateur_id);
-- Une seule adresse par défaut par client
CREATE UNIQUE INDEX uk_adresse_par_defaut ON adresse (utilisateur_id) WHERE par_defaut;

-- Jetons : seule l'empreinte SHA-256 (64 caractères hexadécimaux) est stockée
CREATE TABLE jeton_rafraichissement (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    empreinte          varchar(64)  NOT NULL,
    famille            uuid         NOT NULL,
    date_expiration    timestamptz  NOT NULL,
    date_utilisation   timestamptz,
    revoque            boolean      NOT NULL DEFAULT false,
    adresse_ip         varchar(45),
    user_agent         varchar(255),
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_jeton_rafraichissement_empreinte UNIQUE (empreinte),
    CONSTRAINT ck_jeton_rafraichissement_empreinte CHECK (empreinte ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_jeton_rafraichissement_famille ON jeton_rafraichissement (famille);
CREATE INDEX ix_jeton_rafraichissement_utilisateur ON jeton_rafraichissement (utilisateur_id);
CREATE INDEX ix_jeton_rafraichissement_expiration ON jeton_rafraichissement (date_expiration);

CREATE TABLE jeton_verification_email (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    empreinte          varchar(64)  NOT NULL,
    date_expiration    timestamptz  NOT NULL,
    date_utilisation   timestamptz,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_jeton_verification_email_empreinte UNIQUE (empreinte),
    CONSTRAINT ck_jeton_verification_email_empreinte CHECK (empreinte ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_jeton_verification_email_utilisateur ON jeton_verification_email (utilisateur_id);

CREATE TABLE jeton_reinitialisation_mot_de_passe (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     bigint       NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    empreinte          varchar(64)  NOT NULL,
    date_expiration    timestamptz  NOT NULL,
    date_utilisation   timestamptz,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_jeton_reinitialisation_empreinte UNIQUE (empreinte),
    CONSTRAINT ck_jeton_reinitialisation_empreinte CHECK (empreinte ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_jeton_reinitialisation_utilisateur ON jeton_reinitialisation_mot_de_passe (utilisateur_id);
