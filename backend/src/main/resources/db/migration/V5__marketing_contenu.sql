CREATE TABLE article (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre              varchar(200) NOT NULL,
    slug               varchar(220) NOT NULL,
    extrait            varchar(500),
    contenu            text,
    image_couverture   varchar(500),
    auteur_id          bigint       REFERENCES utilisateur (id) ON DELETE SET NULL,
    nom_auteur         varchar(120) NOT NULL,
    categorie_id       bigint       REFERENCES categorie (id) ON DELETE SET NULL,
    publie             boolean      NOT NULL DEFAULT false,
    date_publication   timestamptz,
    meta_titre         varchar(70),
    meta_description   varchar(170),
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_article_slug UNIQUE (slug),
    CONSTRAINT ck_article_publication CHECK (NOT publie OR date_publication IS NOT NULL)
);
CREATE INDEX ix_article_publie ON article (date_publication DESC) WHERE publie;
CREATE INDEX ix_article_categorie ON article (categorie_id);

CREATE TABLE article_produit (
    article_id  bigint  NOT NULL REFERENCES article (id) ON DELETE CASCADE,
    produit_id  bigint  NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
    position    integer NOT NULL,
    PRIMARY KEY (article_id, position)
);
CREATE INDEX ix_article_produit_produit ON article_produit (produit_id);

CREATE TABLE page_statique (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug               varchar(100) NOT NULL,
    titre              varchar(150) NOT NULL,
    contenu            text         NOT NULL,
    meta_titre         varchar(70),
    meta_description   varchar(170),
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_page_statique_slug UNIQUE (slug)
);
