-- ---------------------------------------------------------------------
CREATE TABLE parametres_site (
    id                         bigint       PRIMARY KEY DEFAULT 1,
    nom_site                   varchar(80)  NOT NULL,
    logo_url                   varchar(500),
    logo_sombre_url            varchar(500),
    favicon_url                varchar(500),
    image_partage_url          varchar(500),
    telephone                  varchar(13),
    whatsapp                   varchar(13),
    email                      varchar(254),
    adresse                    varchar(255),
    horaires                   varchar(255),
    liens_reseaux_sociaux      jsonb        NOT NULL DEFAULT '{}'::jsonb,
    id_google_tag_manager      varchar(20),
    id_ga4                     varchar(20),
    id_google_ads              varchar(20),
    libelle_conversion_achat   varchar(100),
    id_pixel_meta              varchar(20),
    code_verification_google   varchar(100),
    code_verification_meta     varchar(100),
    date_modification          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_parametres_site_ligne_unique CHECK (id = 1),
    CONSTRAINT ck_parametres_site_telephone CHECK (telephone ~ '^\+221(70|75|76|77|78|33)[0-9]{7}$'),
    CONSTRAINT ck_parametres_site_whatsapp CHECK (whatsapp ~ '^\+221(70|75|76|77|78|33)[0-9]{7}$'),
    -- Formats publics des identifiants de suivi (erreurs de saisie détectées tôt)
    CONSTRAINT ck_parametres_site_gtm CHECK (id_google_tag_manager ~ '^GTM-[A-Z0-9]+$'),
    CONSTRAINT ck_parametres_site_ga4 CHECK (id_ga4 ~ '^G-[A-Z0-9]+$'),
    CONSTRAINT ck_parametres_site_google_ads CHECK (id_google_ads ~ '^AW-[0-9]+$'),
    CONSTRAINT ck_parametres_site_pixel_meta CHECK (id_pixel_meta ~ '^[0-9]{10,20}$'),
    CONSTRAINT ck_parametres_site_reseaux CHECK (jsonb_typeof(liens_reseaux_sociaux) = 'object')
);
