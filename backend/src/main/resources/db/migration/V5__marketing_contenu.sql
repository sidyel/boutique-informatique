CREATE TABLE code_promo (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                     varchar(40)  NOT NULL,
    type                     varchar(20)  NOT NULL,
    valeur                   bigint       NOT NULL,
    montant_minimum          bigint       NOT NULL DEFAULT 0,
    date_debut               timestamptz,
    date_fin                 timestamptz,
    utilisations_max         integer,
    utilisations_par_client  integer,
    nombre_utilisations      integer      NOT NULL DEFAULT 0,
    actif                    boolean      NOT NULL DEFAULT true,
    date_creation            timestamptz  NOT NULL DEFAULT now(),
    date_modification        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_code_promo_code UNIQUE (code),
    -- Saisie insensible à la casse : le code est stocké en majuscules, sans espace
    CONSTRAINT ck_code_promo_format CHECK (code ~ '^[A-Z0-9_-]{3,40}$'),
    CONSTRAINT ck_code_promo_type CHECK (type IN ('POURCENTAGE', 'MONTANT_FIXE', 'LIVRAISON_OFFERTE')),
    CONSTRAINT ck_code_promo_valeur CHECK (
        (type = 'POURCENTAGE' AND valeur BETWEEN 1 AND 100)
        OR (type = 'MONTANT_FIXE' AND valeur > 0)
        OR (type = 'LIVRAISON_OFFERTE' AND valeur = 0)),
    CONSTRAINT ck_code_promo_minimum CHECK (montant_minimum >= 0),
    CONSTRAINT ck_code_promo_periode CHECK (date_fin IS NULL OR date_debut IS NULL OR date_fin > date_debut),
    CONSTRAINT ck_code_promo_utilisations CHECK (
        (utilisations_max IS NULL OR utilisations_max > 0)
        AND (utilisations_par_client IS NULL OR utilisations_par_client > 0)
        AND nombre_utilisations >= 0
        AND (utilisations_max IS NULL OR nombre_utilisations <= utilisations_max))
);

CREATE TABLE code_promo_categorie (
    code_promo_id  bigint NOT NULL REFERENCES code_promo (id) ON DELETE CASCADE,
    categorie_id   bigint NOT NULL REFERENCES categorie (id) ON DELETE CASCADE,
    PRIMARY KEY (code_promo_id, categorie_id)
);
CREATE INDEX ix_code_promo_categorie_categorie ON code_promo_categorie (categorie_id);
-- Comptage des utilisations par client
CREATE INDEX ix_commande_code_promo ON commande (code_promo) WHERE code_promo IS NOT NULL;

CREATE TABLE banniere (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emplacement            varchar(30)  NOT NULL,
    categorie_id           bigint       REFERENCES categorie (id) ON DELETE CASCADE,
    image_ordinateur_url   varchar(500) NOT NULL,
    image_mobile_url       varchar(500) NOT NULL,
    texte_alternatif       varchar(255) NOT NULL,
    titre                  varchar(120),
    sous_titre             varchar(255),
    texte_bouton           varchar(40),
    lien                   varchar(500),
    position               integer      NOT NULL DEFAULT 0,
    actif                  boolean      NOT NULL DEFAULT true,
    date_debut             timestamptz,
    date_fin               timestamptz,
    date_creation          timestamptz  NOT NULL DEFAULT now(),
    date_modification      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_banniere_emplacement CHECK (emplacement IN
        ('ACCUEIL_CARROUSEL', 'ACCUEIL_PROMO', 'ENTETE_CATEGORIE', 'TUNNEL_CONFIANCE', 'PIED_DE_PAGE')),
    -- Seul l'en-tête de catégorie est rattaché à une catégorie, et il l'est toujours
    CONSTRAINT ck_banniere_categorie CHECK ((emplacement = 'ENTETE_CATEGORIE') = (categorie_id IS NOT NULL)),
    CONSTRAINT ck_banniere_periode CHECK (date_fin IS NULL OR date_debut IS NULL OR date_fin > date_debut)
);
CREATE INDEX ix_banniere_emplacement ON banniere (emplacement, position) WHERE actif;

CREATE TABLE collection (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre                    varchar(150) NOT NULL,
    slug                     varchar(160) NOT NULL,
    description              text,
    banniere_ordinateur_url  varchar(500),
    banniere_mobile_url      varchar(500),
    indexable                boolean      NOT NULL DEFAULT true,
    actif                    boolean      NOT NULL DEFAULT true,
    date_debut               timestamptz,
    date_fin                 timestamptz,
    meta_titre               varchar(70),
    meta_description         varchar(170),
    date_creation            timestamptz  NOT NULL DEFAULT now(),
    date_modification        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_collection_slug UNIQUE (slug),
    CONSTRAINT ck_collection_periode CHECK (date_fin IS NULL OR date_debut IS NULL OR date_fin > date_debut)
);

CREATE TABLE collection_produit (
    collection_id  bigint  NOT NULL REFERENCES collection (id) ON DELETE CASCADE,
    produit_id     bigint  NOT NULL REFERENCES produit (id) ON DELETE CASCADE,
    position       integer NOT NULL,
    PRIMARY KEY (collection_id, position)
);
CREATE INDEX ix_collection_produit_produit ON collection_produit (produit_id);

-- Conversions envoyées côté serveur (API Conversions Meta, Google Ads)
CREATE TABLE journal_conversion (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id          bigint       NOT NULL REFERENCES commande (id) ON DELETE RESTRICT,
    plateforme           varchar(20)  NOT NULL,
    evenement            varchar(50)  NOT NULL,
    id_evenement         varchar(100) NOT NULL,
    statut               varchar(20)  NOT NULL DEFAULT 'EN_ATTENTE',
    reponse              text,
    nombre_tentatives    integer      NOT NULL DEFAULT 0,
    prochaine_tentative  timestamptz,
    date_creation        timestamptz  NOT NULL DEFAULT now(),
    date_modification    timestamptz  NOT NULL DEFAULT now(),
    -- Jamais deux envois du même événement à la même plateforme
    CONSTRAINT uk_journal_conversion_evenement UNIQUE (plateforme, id_evenement),
    CONSTRAINT ck_journal_conversion_plateforme CHECK (plateforme IN ('META', 'GOOGLE_ADS')),
    CONSTRAINT ck_journal_conversion_statut CHECK (statut IN ('EN_ATTENTE', 'ENVOYEE', 'ECHOUEE', 'ABANDONNEE')),
    CONSTRAINT ck_journal_conversion_tentatives CHECK (nombre_tentatives >= 0)
);
CREATE INDEX ix_journal_conversion_commande ON journal_conversion (commande_id);
-- File des envois à reprendre
CREATE INDEX ix_journal_conversion_a_reprendre ON journal_conversion (prochaine_tentative)
    WHERE statut IN ('EN_ATTENTE', 'ECHOUEE');

