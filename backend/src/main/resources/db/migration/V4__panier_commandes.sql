-- =====================================================================
-- V4 — Panier, zones de livraison, commandes et paiements.
-- Montants en FCFA (bigint). Une commande n'est jamais supprimée et un produit
-- commandé non plus : ligne_commande → variante_produit en ON DELETE RESTRICT
-- (on désactive le produit à la place, voir ADR 0004).
-- =====================================================================

CREATE TABLE zone_livraison (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                varchar(80)  NOT NULL,
    villes_quartiers   jsonb        NOT NULL DEFAULT '[]'::jsonb,
    tarif              bigint       NOT NULL,
    delai_jours        integer      NOT NULL,
    actif              boolean      NOT NULL DEFAULT true,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_zone_livraison_nom UNIQUE (nom),
    CONSTRAINT ck_zone_livraison_tarif CHECK (tarif >= 0),
    CONSTRAINT ck_zone_livraison_delai CHECK (delai_jours >= 0),
    CONSTRAINT ck_zone_livraison_villes CHECK (jsonb_typeof(villes_quartiers) = 'array')
);

-- ---------------------------------------------------------------------
-- Panier : d'un client connecté OU d'un visiteur (jeton en cookie)
-- ---------------------------------------------------------------------
CREATE TABLE panier (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id     bigint       REFERENCES utilisateur (id) ON DELETE CASCADE,
    jeton_invite       varchar(64),
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_panier_utilisateur UNIQUE (utilisateur_id),
    CONSTRAINT uk_panier_jeton_invite UNIQUE (jeton_invite),
    CONSTRAINT ck_panier_proprietaire CHECK (num_nonnulls(utilisateur_id, jeton_invite) = 1)
);
-- Purge des paniers invités abandonnés
CREATE INDEX ix_panier_invite_modification ON panier (date_modification) WHERE jeton_invite IS NOT NULL;

CREATE TABLE ligne_panier (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    panier_id          bigint       NOT NULL REFERENCES panier (id) ON DELETE CASCADE,
    -- Une variante supprimée (jamais commandée) disparaît simplement des paniers
    variante_id        bigint       NOT NULL REFERENCES variante_produit (id) ON DELETE CASCADE,
    quantite           integer      NOT NULL,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_ligne_panier_variante UNIQUE (panier_id, variante_id),
    CONSTRAINT ck_ligne_panier_quantite CHECK (quantite BETWEEN 1 AND 99)
);
CREATE INDEX ix_ligne_panier_variante ON ligne_panier (variante_id);

-- ---------------------------------------------------------------------
-- Commandes
-- ---------------------------------------------------------------------
-- Compteur des numéros lisibles CMD-2026-000123 (sans doublon ; des trous sont possibles après une annulation de transaction)
CREATE SEQUENCE sequence_numero_commande AS bigint START 1;

CREATE TABLE commande (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                     varchar(20)  NOT NULL,
    -- Compte supprimé (droit à l'effacement) : la commande reste, anonymisée par ailleurs
    utilisateur_id             bigint       REFERENCES utilisateur (id) ON DELETE SET NULL,
    email_client               varchar(254) NOT NULL,
    telephone_client           varchar(13)  NOT NULL,
    -- Copie figée de l'adresse (AdresseLivraison)
    livraison_nom_complet      varchar(120),
    livraison_telephone        varchar(13),
    livraison_ville            varchar(80),
    livraison_quartier         varchar(80),
    livraison_adresse_ligne    varchar(255),
    livraison_point_de_repere  varchar(255),
    zone_livraison_id          bigint       REFERENCES zone_livraison (id) ON DELETE RESTRICT,
    mode_livraison             varchar(20)  NOT NULL,
    sous_total                 bigint       NOT NULL,
    frais_livraison            bigint       NOT NULL DEFAULT 0,
    remise                     bigint       NOT NULL DEFAULT 0,
    total                      bigint       NOT NULL,
    code_promo                 varchar(40),
    mode_paiement              varchar(20)  NOT NULL,
    statut                     varchar(30)  NOT NULL DEFAULT 'EN_ATTENTE_PAIEMENT',
    -- Attribution marketing (AttributionMarketing)
    utm_source                 varchar(100),
    utm_medium                 varchar(100),
    utm_campagne               varchar(150),
    utm_contenu                varchar(150),
    utm_terme                  varchar(150),
    gclid                      varchar(255),
    fbclid                     varchar(255),
    fbp                        varchar(100),
    fbc                        varchar(300),
    page_arrivee               varchar(500),
    referent                   varchar(500),
    adresse_ip                 varchar(45),
    user_agent                 varchar(255),
    date_creation              timestamptz  NOT NULL DEFAULT now(),
    date_modification          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_commande_numero UNIQUE (numero),
    CONSTRAINT ck_commande_numero CHECK (numero ~ '^CMD-[0-9]{4}-[0-9]{6,}$'),
    CONSTRAINT ck_commande_telephone CHECK (telephone_client ~ '^\+221(70|75|76|77|78|33)[0-9]{7}$'),
    CONSTRAINT ck_commande_livraison_telephone
        CHECK (livraison_telephone ~ '^\+221(70|75|76|77|78|33)[0-9]{7}$'),
    CONSTRAINT ck_commande_montants_positifs
        CHECK (sous_total >= 0 AND frais_livraison >= 0 AND remise >= 0 AND total >= 0),
    -- Le total est toujours cohérent, quel que soit le chemin d'écriture
    CONSTRAINT ck_commande_total CHECK (total = greatest(0, sous_total + frais_livraison - remise)),
    CONSTRAINT ck_commande_mode_livraison CHECK (mode_livraison IN ('DOMICILE', 'RETRAIT_MAGASIN')),
    -- Livraison à domicile : adresse complète et zone obligatoires
    CONSTRAINT ck_commande_adresse_domicile CHECK (
        mode_livraison <> 'DOMICILE'
        OR (livraison_nom_complet IS NOT NULL AND livraison_telephone IS NOT NULL
            AND livraison_ville IS NOT NULL AND livraison_quartier IS NOT NULL
            AND zone_livraison_id IS NOT NULL)),
    CONSTRAINT ck_commande_mode_paiement
        CHECK (mode_paiement IN ('WAVE', 'ORANGE_MONEY', 'FREE_MONEY', 'CARTE_BANCAIRE', 'A_LA_LIVRAISON')),
    CONSTRAINT ck_commande_statut CHECK (statut IN ('EN_ATTENTE_PAIEMENT', 'CONFIRMEE', 'PAYEE',
        'EN_PREPARATION', 'EXPEDIEE', 'LIVREE', 'ANNULEE', 'REMBOURSEE'))
);
CREATE INDEX ix_commande_utilisateur ON commande (utilisateur_id, date_creation DESC);
CREATE INDEX ix_commande_statut ON commande (statut, date_creation DESC);
CREATE INDEX ix_commande_date ON commande (date_creation DESC);
CREATE INDEX ix_commande_telephone ON commande (telephone_client);
CREATE INDEX ix_commande_email ON commande (lower(email_client));

CREATE TABLE ligne_commande (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id        bigint       NOT NULL REFERENCES commande (id) ON DELETE CASCADE,
    -- Un produit déjà commandé n'est jamais supprimé physiquement : on le désactive
    variante_id        bigint       NOT NULL,
    nom_produit        varchar(200) NOT NULL,
    sku                varchar(64)  NOT NULL,
    libelle_variante   varchar(150) NOT NULL,
    image_url          varchar(500),
    prix_unitaire      bigint       NOT NULL,
    quantite           integer      NOT NULL,
    total_ligne        bigint       NOT NULL,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_ligne_commande_variante FOREIGN KEY (variante_id)
        REFERENCES variante_produit (id) ON DELETE RESTRICT,
    CONSTRAINT ck_ligne_commande_quantite CHECK (quantite > 0),
    CONSTRAINT ck_ligne_commande_prix CHECK (prix_unitaire >= 0),
    CONSTRAINT ck_ligne_commande_total CHECK (total_ligne = prix_unitaire * quantite)
);
CREATE INDEX ix_ligne_commande_commande ON ligne_commande (commande_id);
CREATE INDEX ix_ligne_commande_variante ON ligne_commande (variante_id);

CREATE TABLE historique_statut_commande (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id        bigint       NOT NULL REFERENCES commande (id) ON DELETE CASCADE,
    ancien_statut      varchar(30),
    nouveau_statut     varchar(30)  NOT NULL,
    auteur             varchar(254) NOT NULL,
    commentaire        text,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_historique_statut_commande ON historique_statut_commande (commande_id, date_creation);

CREATE TABLE paiement (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Trace financière : jamais supprimée avec la commande
    commande_id        bigint       NOT NULL REFERENCES commande (id) ON DELETE RESTRICT,
    fournisseur        varchar(20)  NOT NULL,
    reference_externe  varchar(120),
    montant            bigint       NOT NULL,
    statut             varchar(20)  NOT NULL DEFAULT 'EN_ATTENTE',
    donnees_brutes     jsonb,
    date_creation      timestamptz  NOT NULL DEFAULT now(),
    date_modification  timestamptz  NOT NULL DEFAULT now(),
    -- Idempotence des webhooks : une référence prestataire = un seul paiement
    CONSTRAINT uk_paiement_reference UNIQUE (fournisseur, reference_externe),
    CONSTRAINT ck_paiement_montant CHECK (montant >= 0),
    CONSTRAINT ck_paiement_fournisseur
        CHECK (fournisseur IN ('STRIPE', 'PAYDUNYA', 'CINETPAY', 'WAVE', 'ORANGE_MONEY', 'A_LA_LIVRAISON')),
    CONSTRAINT ck_paiement_statut CHECK (statut IN ('EN_ATTENTE', 'REUSSI', 'ECHOUE', 'ANNULE', 'REMBOURSE'))
);
CREATE INDEX ix_paiement_commande ON paiement (commande_id);
